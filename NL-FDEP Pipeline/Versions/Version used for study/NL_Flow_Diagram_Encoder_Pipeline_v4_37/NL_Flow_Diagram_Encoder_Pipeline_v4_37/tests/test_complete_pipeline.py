import json
import tempfile
import unittest
from pathlib import Path

from aj_parser import AJParserFacade
from aj_python_compiler import AJPythonCompiler
from aj_test_harness import AJTestHarness, TestCase
from flow_diagram import FlowDiagramEncoder
from flow_diagram_visualizer import FlowDiagramVisualizer
from drawio_exporter import DrawIOFlowExporter
from xml.etree import ElementTree
from nl_flow_pipeline import NLFlowDiagramEncoderPipeline


SAMPLE = """
total <- INTEGER(0)
FOR number <- IN RANGE INTEGER(1) TO INTEGER(4) DO
    total <- total + number
ENDFOR
OUTPUT total
""".strip()

EXPECTED_PYTHON = """\
\"\"\"Generated by the NL to Flow Diagram Encoder Pipeline.\"\"\"

total = 0

for number in range(1, 4):
    total = (total + number)

print(total)
"""


class CompletePipelineTests(unittest.TestCase):

    def test_pseudocode_generates_flow_diagram(self):
        parse_result = AJParserFacade().parse(SAMPLE)
        self.assertTrue(parse_result.success, parse_result.report.pretty())

        flow_diagram = FlowDiagramEncoder().encode(parse_result.ast)
        document = flow_diagram.to_dict()

        self.assertEqual(document["format"], "NL-FDEP Flow Diagram")
        self.assertGreater(len(document["nodes"]), 3)
        self.assertEqual(document["structured_program"]["kind"], "ProgramNode")

    def test_flow_diagram_compiles_to_python(self):
        parse_result = AJParserFacade().parse(SAMPLE)
        flow_diagram = FlowDiagramEncoder().encode(parse_result.ast)
        compilation = AJPythonCompiler().compile(flow_diagram)

        self.assertTrue(compilation.success)
        self.assertIn("for number in range", compilation.source_code)
        self.assertIn("print(total)", compilation.source_code)


    def test_plain_variable_output_compiles_without_f_string(self):
        parse_result = AJParserFacade().parse("OUTPUT total")
        flow_diagram = FlowDiagramEncoder().encode(parse_result.ast)
        compilation = AJPythonCompiler().compile(flow_diagram)

        self.assertTrue(compilation.success)
        self.assertIn("print(total)", compilation.source_code)
        self.assertNotIn("print(ftotal)", compilation.source_code)

    def test_formatted_string_output_compiles_to_python_f_string(self):
        pseudocode = """
        total <- INTEGER(10)
        OUTPUT STRING("The total is {total}")
        """.strip()

        parse_result = AJParserFacade().parse(pseudocode)
        self.assertTrue(parse_result.success, parse_result.report.pretty())

        flow_diagram = FlowDiagramEncoder().encode(parse_result.ast)
        compilation = AJPythonCompiler().compile(flow_diagram)

        self.assertTrue(compilation.success)
        self.assertIn(
            "print(f'The total is {total}')",
            compilation.source_code,
        )

    def test_saved_flow_diagram_compiles_to_exact_reference_python(self):
        parse_result = AJParserFacade().parse(SAMPLE)
        flow_diagram = FlowDiagramEncoder().encode(parse_result.ast)

        serialized_document = json.loads(flow_diagram.to_json())
        compilation = AJPythonCompiler().compile(serialized_document)

        self.assertTrue(compilation.success)
        self.assertEqual(compilation.source_code, EXPECTED_PYTHON)

    def test_reference_compilation_executes_with_expected_output(self):
        parse_result = AJParserFacade().parse(SAMPLE)
        flow_diagram_document = json.loads(
            FlowDiagramEncoder().encode(parse_result.ast).to_json()
        )
        compilation = AJPythonCompiler().compile(flow_diagram_document)

        with tempfile.TemporaryDirectory() as temporary_directory:
            program_path = Path(temporary_directory) / "compiled_from_flow.py"
            program_path.write_text(compilation.source_code, encoding="utf-8")
            report = AJTestHarness().run(
                program_path,
                [TestCase("Compiled flow reference", expected_output=["6"])],
            )

        self.assertTrue(report.success, report.to_json())

    def test_flow_visualisation_opens_at_readable_scale(self):
        parse_result = AJParserFacade().parse(SAMPLE)
        flow_diagram = FlowDiagramEncoder().encode(parse_result.ast)

        with tempfile.TemporaryDirectory() as temporary_directory:
            output_path = FlowDiagramVisualizer().generate(
                flow_diagram,
                Path(temporary_directory) / "flow_diagram.html",
            )
            html_document = output_path.read_text(encoding="utf-8")

        self.assertIn("const INITIAL_SCALE = 1.15", html_document)
        self.assertIn("window.addEventListener('load', initialView)", html_document)
        self.assertIn("translateY = 28 - box.y * scale", html_document)


    def test_generated_flow_diagram_exports_editable_drawio_xml(self):
        parse_result = AJParserFacade().parse(SAMPLE)
        flow_diagram = FlowDiagramEncoder().encode(parse_result.ast)

        with tempfile.TemporaryDirectory() as temporary_directory:
            output_path = DrawIOFlowExporter().export(
                flow_diagram,
                Path(temporary_directory) / "flow_diagram.drawio",
            )
            root = ElementTree.parse(output_path).getroot()

        self.assertEqual(root.tag, "mxfile")
        graph_model = root.find("./diagram/mxGraphModel")
        self.assertIsNotNone(graph_model)
        cells = root.findall("./diagram/mxGraphModel/root/mxCell")
        vertex_ids = {cell.get("id") for cell in cells if cell.get("vertex") == "1"}
        edge_cells = [cell for cell in cells if cell.get("edge") == "1"]
        self.assertIn(flow_diagram.entry_node, vertex_ids)
        self.assertIn(flow_diagram.exit_node, vertex_ids)
        self.assertEqual(len(edge_cells), len(flow_diagram.edges))

        start_cell = next(
            cell
            for cell in cells
            if cell.get("id") == flow_diagram.entry_node
        )
        start_geometry = start_cell.find("mxGeometry")
        self.assertEqual(start_geometry.get("x"), "265")
        self.assertEqual(start_geometry.get("width"), "230")
        self.assertIn("fontFamily=Arial", start_cell.get("style"))
        self.assertIn("strokeWidth=1.6", start_cell.get("style"))
        self.assertIn("Line 1", start_cell.get("value"))

        function_source = """
FUNCTION find_largest ACCEPTS(numbers AS LIST)
    RETURN numbers[0]
ENDFUNCTION
""".strip()
        function_parse_result = AJParserFacade().parse(function_source)
        function_diagram = FlowDiagramEncoder().encode(function_parse_result.ast)

        with tempfile.TemporaryDirectory() as function_directory:
            function_path = DrawIOFlowExporter().export(
                function_diagram,
                Path(function_directory) / "function.drawio",
            )
            function_root = ElementTree.parse(function_path).getroot()

        function_cells = function_root.findall(
            "./diagram/mxGraphModel/root/mxCell"
        )
        function_cell = next(
            cell
            for cell in function_cells
            if cell.get("vertex") == "1"
            and "shape=process" in cell.get("style", "")
        )
        self.assertEqual(function_cell.get("value"), "")
        function_geometry = function_cell.find("mxGeometry")
        self.assertEqual(function_geometry.get("width"), "230")

        function_label_cell = next(
            cell
            for cell in function_cells
            if cell.get("id") == f"{function_cell.get('id')}_LABEL"
        )
        self.assertIn("connectable=0", function_label_cell.get("style"))
        self.assertIn("Run function", function_label_cell.get("value"))
        function_label_geometry = function_label_cell.find("mxGeometry")
        self.assertEqual(function_label_geometry.get("x"), function_geometry.get("x"))
        self.assertEqual(function_label_geometry.get("width"), "230")

        routed_edges = [
            edge_cell
            for edge_cell in edge_cells
            if edge_cell.find("./mxGeometry/Array[@as='points']") is not None
        ]
        self.assertEqual(len(routed_edges), len(flow_diagram.edges))
        self.assertTrue(
            all(
                "strokeWidth=1.45" in edge_cell.get("style")
                for edge_cell in edge_cells
            )
        )

    def test_generated_python_passes_harness(self):
        parse_result = AJParserFacade().parse(SAMPLE)
        flow_diagram = FlowDiagramEncoder().encode(parse_result.ast)
        compilation = AJPythonCompiler().compile(flow_diagram)

        with tempfile.TemporaryDirectory() as temporary_directory:
            program_path = Path(temporary_directory) / "generated_program.py"
            program_path.write_text(compilation.source_code, encoding="utf-8")
            report = AJTestHarness().run(
                program_path,
                [TestCase("Range total", expected_output=["6"])],
            )

        self.assertTrue(report.success, report.to_json())

    def test_complete_pipeline_outputs_expected_files(self):
        with tempfile.TemporaryDirectory() as temporary_directory:
            result = NLFlowDiagramEncoderPipeline().run(
                pseudocode=SAMPLE,
                output_directory=Path(temporary_directory),
                test_cases=[TestCase("Range total", expected_output=["6"])],
                open_visualisations=False,
            )

            self.assertTrue(result.success, result.to_json())
            self.assertTrue(Path(result.output_files["flow_diagram"]).exists())
            self.assertTrue(Path(result.output_files["generated_python"]).exists())
            self.assertTrue(Path(result.output_files["flow_diagram_drawio"]).exists())
            self.assertTrue(Path(result.output_files["test_report"]).exists())

            flow_document = json.loads(
                Path(result.output_files["flow_diagram"]).read_text(
                    encoding="utf-8"
                )
            )
            self.assertEqual(flow_document["version"], "1.0")


if __name__ == "__main__":
    unittest.main()

class TerminalErrorBranchLayoutTests(unittest.TestCase):

    def test_raise_branch_routes_sideways_and_normal_flow_continues_down(self):
        pseudocode = """
FUNCTION find_largest ACCEPTS(numbers AS LIST)
    IF LENGTH OF numbers == 0 THEN
        RAISE STRING("The list cannot be empty")
    ENDIF
    largest <- numbers[0]
    RETURN largest
ENDFUNCTION
""".strip()

        parse_result = AJParserFacade().parse(pseudocode)
        self.assertTrue(parse_result.success, parse_result.report.pretty())

        flow_diagram = FlowDiagramEncoder().encode(parse_result.ast)
        nodes = flow_diagram.nodes
        edges = flow_diagram.edges

        decision_id = next(
            node_id
            for node_id, node in nodes.items()
            if node.node_type == "DECISION"
        )
        raise_id = next(
            node_id
            for node_id, node in nodes.items()
            if node.node_type == "RAISE"
        )
        assignment_id = next(
            node_id
            for node_id, node in nodes.items()
            if node.node_type == "PROCESS"
        )
        error_end_id = next(
            node_id
            for node_id, node in nodes.items()
            if node.node_type == "END" and node.label == "End after error"
        )

        self.assertTrue(any(
            edge.source == decision_id
            and edge.target == raise_id
            and edge.label == "TRUE"
            for edge in edges
        ))
        self.assertTrue(any(
            edge.source == decision_id
            and edge.target == assignment_id
            and edge.label == "FALSE"
            for edge in edges
        ))
        self.assertTrue(any(
            edge.source == raise_id
            and edge.target == error_end_id
            for edge in edges
        ))
        self.assertFalse(any(
            edge.source == raise_id
            and edge.target == assignment_id
            for edge in edges
        ))

        positions = FlowDiagramVisualizer()._calculate_positions(flow_diagram)
        decision_x, decision_y = positions[decision_id]
        raise_x, raise_y = positions[raise_id]
        assignment_x, assignment_y = positions[assignment_id]

        self.assertGreater(raise_x, decision_x)
        self.assertAlmostEqual(assignment_x, decision_x)
        self.assertGreater(assignment_y, decision_y)
